/** ARPAbet with optional CMU stress digits, normalized to uppercase symbols. */
export const arpabet: NotationDefinition = {
  id: ARPABET,
  toIpa,
  fromIpa,
  tokenize(input) {
    return tokenizeWhitespace(input).map((token) => token.replace(/\d+$/, "").toLowerCase());
  },
};
